/// Bit mask rows for a character (bit 3 = leftmost pixel).
pub fn glyph(c: char) -> [u8; 5] {
    let c = c.to_ascii_uppercase();
    let rows = GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map(|(_, r)| *r)
        // Unknown characters render as a filled box, like missing glyphs in game.
        .unwrap_or(["####", "#..#", "#..#", "#..#", "####"]);
    let mut out = [0u8; 5];
    for (i, row) in rows.iter().enumerate() {
        for (j, ch) in row.bytes().enumerate() {
            if ch == b'#' {
                out[i] |= 1 << (3 - j);
            }
        }
    }
    out
}
